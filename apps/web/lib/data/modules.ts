/**
 * Lookup helpers — keep callers from scanning the array.
 */
export function getModuleBySlug(slug: string): Module | undefined {
  return MODULES.find((m) => m.slug === slug);
}

export function getModulesByCategory(category: Module["category"]) {
  return MODULES.filter((m) => m.category === category);
}

export function getPreviewableModules() {
  return MODULES.filter((m) => m.previewable);
}

